// Dependency inventory and license gate.
//   reports/dependency-licenses.json   every installed package (name, version, license, shipped?)
//   docs/engineering/dependency-inventory.md   direct dependencies
// Fails when shipped code (the API/worker image closure plus the browser bundle's runtime
// dependencies) uses a license outside the allow-list. Licenses are read from each installed
// package's own package.json at the path reported by `pnpm list`.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ALLOWED = new Set([
  'MIT',
  'ISC',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  '0BSD',
  'BlueOak-1.0.0',
  'Python-2.0',
  'CC0-1.0',
  'Unlicense',
  'MIT-0',
  'CC-BY-4.0',
]);
const pnpmList = (args) =>
  JSON.parse(
    execFileSync('pnpm', ['list', '--json', '--depth', 'Infinity', ...args], {
      encoding: 'utf8',
      maxBuffer: 256 * 1024 * 1024,
    }),
  );

const packages = new Map(); // key name@version -> { name, version, license, shipped }
const licenseAt = (path) => {
  try {
    const json = JSON.parse(readFileSync(join(path, 'package.json'), 'utf8'));
    const l = json.license ?? json.licenses;
    return typeof l === 'string'
      ? l
      : Array.isArray(l)
        ? l.map((x) => x.type ?? x).join(' OR ')
        : (l?.type ?? 'UNKNOWN');
  } catch {
    return 'UNKNOWN';
  }
};
const walk = (deps, shipped) => {
  for (const [name, info] of Object.entries(deps ?? {})) {
    if (name.startsWith('@pm/')) {
      walk(info.dependencies, shipped);
      continue;
    }
    const key = `${name}@${info.version}`;
    const entry = packages.get(key) ?? {
      name,
      version: info.version,
      license: licenseAt(info.path),
      shipped: false,
    };
    const seen = packages.has(key) && (entry.shipped || !shipped);
    entry.shipped ||= shipped;
    packages.set(key, entry);
    if (!seen) walk(info.dependencies, shipped);
  }
};
for (const p of pnpmList(['-r'])) {
  walk(p.dependencies, false);
  walk(p.devDependencies, false);
}
for (const p of pnpmList([
  '--prod',
  '--filter',
  '@pm/api',
  '--filter',
  '@pm/worker',
  '--filter',
  '@pm/web',
]))
  walk(p.dependencies, true);

const allowed = (license) =>
  license
    .split(/\s+OR\s+|[()]/)
    .map((s) => s.trim())
    .filter(Boolean)
    .some((l) => ALLOWED.has(l));
const all = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name));
const shipped = all.filter((p) => p.shipped);
const violations = shipped.filter((p) => !allowed(p.license));

mkdirSync('reports', { recursive: true });
writeFileSync(
  'reports/dependency-licenses.json',
  JSON.stringify({ allowList: [...ALLOWED], packages: all }, null, 2),
);

const direct = new Map();
const addDirect = (owner, deps, kind) => {
  for (const [dep, version] of Object.entries(deps ?? {})) {
    if (dep.startsWith('@pm/')) continue;
    const e = direct.get(dep) ?? { version, users: new Set(), kinds: new Set() };
    e.users.add(owner);
    e.kinds.add(kind);
    direct.set(dep, e);
  }
};
for (const base of ['apps', 'packages']) {
  for (const name of readdirSync(base)) {
    const file = `${base}/${name}/package.json`;
    if (!existsSync(file)) continue;
    const json = JSON.parse(readFileSync(file, 'utf8'));
    addDirect(json.name, json.dependencies, 'runtime');
    addDirect(json.name, json.devDependencies, 'dev');
  }
}
addDirect(
  '(root tooling)',
  JSON.parse(readFileSync('package.json', 'utf8')).devDependencies,
  'dev',
);
const lic = (name, version) => packages.get(`${name}@${version}`)?.license ?? 'UNKNOWN';
const byLicense = Object.entries(Object.groupBy(shipped, (p) => p.license))
  .map(([l, ps]) => `${l} (${ps.length})`)
  .join(', ');
const rows = [...direct.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(
    ([name, e]) =>
      `| \`${name}\` | ${e.version} | ${lic(name, e.version)} | ${[...e.kinds].join(', ')} | ${[...e.users].join(', ')} |`,
  );
writeFileSync(
  'docs/engineering/dependency-inventory.md',
  `# Dependency inventory

Generated by \`pnpm deps:licenses\` (scripts/dependency-report.mjs). Do not edit by hand.
Machine-readable report with every installed package: \`reports/dependency-licenses.json\` (CI artifact).

- Direct third-party dependencies: ${direct.size}
- Installed packages (including transitive and build/test tooling): ${all.length}
- Shipped packages (API/worker image closure + browser runtime): ${shipped.length}
- Shipped licenses: ${byLicense}
- Allow-list for shipped code: ${[...ALLOWED].join(', ')}
- Shipped license violations: ${violations.length}

| Package | Version (exact) | License | Kind | Used by |
|---|---|---|---|---|
${rows.join('\n')}

Update policy: see [ADR-0006](adr/0006-dependency-policy.md).
`,
);
if (violations.length) {
  console.error(
    `Shipped dependencies with disallowed licenses:\n  ${violations.map((v) => `${v.name}@${v.version}: ${v.license}`).join('\n  ')}`,
  );
  process.exit(1);
}
console.log(
  `dependency report: ${direct.size} direct, ${all.length} installed, ${shipped.length} shipped; licenses: ${byLicense}; no violations`,
);
